"""Synthetic "CAM-like" program for parts/dev/motor_mount, used to test the simulator and the report viewer at scale.

    python tests/make_big_program.py [out.nc] [--finish-step 0.5]

Operations (all hand-rolled, no CAM library):
  T1  10 mm flat   face the top 18 -> 16 in two passes (zig-zag)
  T2   6 mm flat   outer profile (R11 offset path) in 2 mm steps; spiral-out pocket D40 x 6; spiral-out through bore D22;
                   zig-zag pocket 30 x 20 x 8 around the D10 island (keep-out arc); trochoidal through slot
  T10  5 mm drill  G83 peck drilling of the four D6.6 holes
  T3   3 mm flat   helical interpolation of the D6.6 holes and D11 counterbores
  T9   chamfer     1 mm x 45 deg chamfer on the outer top edge
  T6   6 mm ball   3D drop-cutter raster finish of the whole top (dense: 25k+ points) using the target height field
The result is not a perfect program (the ball raster dives into holes, some corners are left), which is what we want
for test data: a realistic mix of in-tolerance, proud and (a little) gouged surface, 50k+ moves.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

SAFE = 22.0
OUT: list[str] = []


def emit(s: str):
    OUT.append(s)


def f(v: float) -> str:
    s = f"{v:.4f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def g1(x=None, y=None, z=None, F=None):
    w = ["G1"]
    if x is not None:
        w.append("X" + f(x))
    if y is not None:
        w.append("Y" + f(y))
    if z is not None:
        w.append("Z" + f(z))
    if F is not None:
        w.append("F" + f(F))
    emit(" ".join(w))


def g0(x=None, y=None, z=None):
    w = ["G0"]
    if x is not None:
        w.append("X" + f(x))
    if y is not None:
        w.append("Y" + f(y))
    if z is not None:
        w.append("Z" + f(z))
    emit(" ".join(w))


def tool(n: int, rpm: int, name: str):
    emit(f"(--- T{n}: {name} ---)")
    emit("G0 Z" + f(SAFE + 20))
    emit("M5")
    emit("M9")
    emit(f"T{n} M6")
    emit(f"G43 H{n}")
    emit(f"S{rpm} M3")
    emit("M8")


def helix_entry(cx, cy, r, z_from, z_to, F, pitch=1.0):
    """Helical ramp down at (cx, cy) radius r from z_from to z_to, 36 segments per turn."""
    g0(cx + r, cy)
    g0(z=z_from + 1.0)
    g1(z=z_from, F=F)
    turns = max((z_from - z_to) / pitch, 0.25)
    n = int(math.ceil(turns * 36))
    for k in range(1, n + 1):
        a = 2 * math.pi * turns * k / n
        g1(cx + r * math.cos(a), cy + r * math.sin(a), z_from + (z_to - z_from) * k / n)
    for k in range(1, 37):  # flat cleanup turn at depth
        a = 2 * math.pi * k / 36
        g1(cx + r * math.cos(a), cy + r * math.sin(a))


def spiral_out(cx, cy, r0, r1, step, z, F):
    """Archimedean spiral from radius r0 to r1 (stepover `step` per turn), 1 mm chords, then a finishing circle."""
    a = 0.0
    r = r0
    while r < r1:
        da = min(1.0 / max(r, 0.5), 0.4)
        a += da
        r = min(r0 + step * a / (2 * math.pi), r1)
        g1(cx + r * math.cos(a), cy + r * math.sin(a), F=F if a == da else None)
    n = int(max(36, 2 * math.pi * r1 / 0.8))
    for k in range(1, n + 1):
        b = a + 2 * math.pi * k / n
        g1(cx + r1 * math.cos(b), cy + r1 * math.sin(b))


def rounded_rect(hx, hy, rc, cx=0.0, cy=0.0, chord=1.0):
    """Closed CCW path of a rounded rectangle (half extents hx, hy, corner radius rc) starting at the +X middle."""
    pts = []
    corners = [(hx - rc, hy - rc, 0.0), (-hx + rc, hy - rc, 0.5 * math.pi), (-hx + rc, -hy + rc, math.pi),
               (hx - rc, -hy + rc, 1.5 * math.pi)]
    pts.append((cx + hx, cy))
    na = max(int(0.5 * math.pi * rc / chord), 6)
    for (ox, oy, a0) in corners:
        for k in range(na + 1):
            a = a0 + 0.5 * math.pi * k / na
            pts.append((cx + ox + rc * math.cos(a), cy + oy + rc * math.sin(a)))
    pts.append((cx + hx, cy))
    return pts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("out", nargs="?", default="big_motor_mount.nc")
    ap.add_argument("--finish-step", type=float, default=0.6, help="ball raster stepover (mm)")
    ap.add_argument("--finish-pitch", type=float, default=0.3, help="ball raster point spacing (mm)")
    a = ap.parse_args()

    from cncllm import part as part_mod
    p = part_mod.load(REPO / "parts" / "dev" / "motor_mount", verbose=False)

    emit("%")
    emit("(motor_mount - synthetic test program generated by tests/make_big_program.py)")
    emit("G21 G90 G17 G40 G49 G80 G94")

    # ---- T1 facing
    tool(1, 15000, "10 mm flat, face 18 -> 16")
    for zf in (17.0, 16.0):
        g0(-58, -40)
        g0(z=SAFE)
        g0(z=zf + 1)
        g1(z=zf, F=600)
        y = -40.0
        d = 1
        first = True
        while y <= 40.0:
            g1(58 * d, F=2400 if first else None)
            first = False
            y += 7.0
            if y <= 40.0:
                g1(y=y)
            d = -d
        g0(z=SAFE)

    # ---- T2 6 mm flat
    tool(2, 18000, "6 mm flat, profile / pockets / bore / slot")
    path = rounded_rect(53.0, 38.0, 11.0)
    g0(path[0][0] + 4, path[0][1])
    g0(z=SAFE)
    g0(z=17)
    z = 16.0
    while z > -0.2:
        z = max(z - 2.0, -0.2)
        g1(path[0][0] + 4, path[0][1], z, F=800)
        g1(path[0][0], path[0][1], F=1800)
        for (x, y) in path[1:]:
            g1(x, y)
        g1(path[0][0] + 4, path[0][1])
    g0(z=SAFE)
    # central pocket D40 x 6 deep at (-15, 0): spiral out at each 1.5 mm level, tool radius 3 -> r1 = 17
    cx, cy = -15.0, 0.0
    levels = [14.5, 13.0, 11.5, 10.0]
    helix_entry(cx, cy, 1.5, 16.0, levels[0], 700)
    for i, zl in enumerate(levels):
        if i:
            g1(cx + 1.5, cy, F=1800)
            for k in range(1, 37):
                aa = 2 * math.pi * k / 36
                g1(cx + 1.5 * math.cos(aa), cy + 1.5 * math.sin(aa), zl + (levels[i - 1] - zl) * (1 - k / 36), F=700)
        spiral_out(cx, cy, 1.5, 17.0, 2.4, zl, 1800)
        g1(cx + 1.5, cy, F=1800)
    # D22 through bore: r1 = 8
    zb = 10.0
    while zb > -0.2:
        zn = max(zb - 1.5, -0.2)
        g1(cx + 1.5, cy, F=1800)
        for k in range(1, 37):
            aa = 2 * math.pi * k / 36
            g1(cx + 1.5 * math.cos(aa), cy + 1.5 * math.sin(aa), zb + (zn - zb) * k / 36, F=700)
        spiral_out(cx, cy, 1.5, 8.0, 2.4, zn, 1800)
        zb = zn
    g0(z=SAFE)
    # rectangular pocket 30 x 20 (x 15..45, y -22..-2) floor Z8, island D10 at (30, -12) to Z13
    px0, px1, py0, py1 = 15 + 3.0, 45 - 3.0, -22 + 3.0, -2 - 3.0
    ix, iy, keep = 30.0, -12.0, 5.0 + 3.0
    zl = 16.0
    first = True
    while zl > 8.0:
        zl = max(zl - 1.5, 8.0)
        isl_top = 13.0
        g0(px0, py0)
        if first:
            g0(z=17)
            first = False
        # ramp entry along the first row
        g1(px0 + 6, py0, zl + 0.75, F=700)
        g1(px0, py0, zl)
        y = py0
        d = 1
        while y <= py1 + 1e-9:
            xa, xb = (px0, px1) if d > 0 else (px1, px0)
            dy = y - iy
            if zl < isl_top and abs(dy) < keep:
                half = math.sqrt(keep * keep - dy * dy)
                xs = ix - d * half
                xe = ix + d * half
                g1(xs, y, F=1800)
                # go around the island on the keep-out arc (side away from the next row's direction)
                a0 = math.atan2(dy, xs - ix)
                a1 = math.atan2(dy, xe - ix)
                if dy >= 0:   # upper side: arc through +y
                    sweep = (a1 - a0) % (2 * math.pi) if d < 0 else -((a0 - a1) % (2 * math.pi))
                else:
                    sweep = -((a0 - a1) % (2 * math.pi)) if d < 0 else (a1 - a0) % (2 * math.pi)
                if abs(sweep) > math.pi:
                    sweep = sweep - math.copysign(2 * math.pi, sweep)
                n = max(int(abs(sweep) * keep / 0.6), 4)
                for k in range(1, n + 1):
                    aa = a0 + sweep * k / n
                    g1(ix + keep * math.cos(aa), iy + keep * math.sin(aa))
                g1(xb, y)
            else:
                g1(xb, y, F=1800)
            y += 2.0
            if y <= py1 + 1e-9:
                g1(y=y)
            d = -d
        # wall finishing contour at this level (rounded rect R3 -> tool centre path R0.01)
        rr = rounded_rect(15 - 3, 10 - 3, 0.01, 30, -12)
        g1(rr[0][0], rr[0][1])
        for (x, yy) in rr[1:]:
            g1(x, yy)
        # island contour
        g1(ix + keep, iy)
        for k in range(1, 73):
            aa = 2 * math.pi * k / 72
            g1(ix + keep * math.cos(aa), iy + keep * math.sin(aa))
        g0(z=17)
    g0(z=SAFE)
    # trochoidal through slot: obround 25 x 8 centred (30, 16), tool centre line x 21.5..38.5 (R1 loops)
    zs = 16.0
    g0(21.5, 16)
    g0(z=17)
    while zs > -0.2:
        zs = max(zs - 3.0, -0.2)
        g1(21.5, 16, zs + 0.0, F=500)
        x = 21.5
        aa = 0.0
        while x < 38.5:
            for k in range(24):
                aa += 2 * math.pi / 24
                x = min(x + 0.3 / 24, 38.5)
                g1(x - 0.0 + 1.0 * math.cos(aa) - 1.0, 16 + 1.0 * math.sin(aa), F=1800 if k == 0 else None)
        # finishing pass of the slot walls (tool centre offset 1 from the centre line)
        g1(38.5, 17)
        g1(21.5, 17)
        for k in range(1, 19):
            b = 0.5 * math.pi + math.pi * k / 18
            g1(21.5 + math.cos(b), 16 + math.sin(b))
        g1(38.5, 15)
        for k in range(1, 19):
            b = -0.5 * math.pi + math.pi * k / 18
            g1(38.5 + math.cos(b), 16 + math.sin(b))
        g1(21.5, 16)
    g0(z=SAFE)

    # ---- T10 drill
    holes = [(-38, -25), (-38, 25), (8, -25), (8, 25)]
    tool(10, 6000, "5 mm drill, peck drill the D6.6 holes")
    g0(holes[0][0], holes[0][1])
    g0(z=SAFE)
    emit(f"G98 G83 X{f(holes[0][0])} Y{f(holes[0][1])} Z-0.4 R17 Q3 F300")
    for (x, y) in holes[1:]:
        emit(f"X{f(x)} Y{f(y)}")
    emit("G80")
    g0(z=SAFE)

    # ---- T3 holes D6.6 through and counterbores D11 to Z9.5
    tool(3, 20000, "3 mm flat, helical hole and counterbore milling")
    for (x, y) in holes:
        # counterbore D11: helix rings r = 4.0, 2.5 (tool r 1.5)
        for r in (2.5, 4.0):
            helix_entry(x, y, r, 16.0, 9.5, 600, pitch=0.6)
            g0(z=17)
        helix_entry(x, y, 1.8, 9.5, -0.3, 500, pitch=0.5)
        g0(z=17)
    g0(z=SAFE)

    # ---- T9 chamfer the outer top edge: cone 45 deg, tip r 0.1; axis 1 mm outside the wall, tip at Z14.1
    tool(9, 15000, "chamfer mill, 1 x 45 outer edge")
    ch = rounded_rect(51.0, 36.0, 9.0, chord=0.5)
    g0(ch[0][0] + 3, ch[0][1])
    g0(z=SAFE)
    g0(z=15)
    g1(z=14.1, F=400)
    g1(ch[0][0], ch[0][1], F=500)
    for (x, y) in ch[1:]:
        g1(x, y)
    g1(ch[0][0] + 3, ch[0][1])
    g0(z=SAFE)

    # ---- T6 ball drop-cutter raster finish of the top
    tool(6, 18000, "6 mm ball, 3D raster finish (drop cutter on the target height field)")
    g = p.grid
    Ht = p.Ht
    R = 3.0
    k = 4   # sample the 0.05 mm target field at 0.2 mm for the drop cutter
    H2 = Ht[::k, ::k]
    r2 = g["res"] * k
    xs2 = g["x0"] + (np.arange(H2.shape[1]) * k + 0.5) * g["res"]
    ys2 = g["y0"] + (np.arange(H2.shape[0]) * k + 0.5) * g["res"]
    nr = int(math.ceil(R / r2))
    di, dj = np.mgrid[-nr:nr + 1, -nr:nr + 1]
    dd = np.hypot(di * r2, dj * r2)
    m = dd <= R
    di, dj, prof = di[m], dj[m], R - np.sqrt(np.maximum(R * R - dd[m] ** 2, 0))

    def drop(X, Y):
        jj = np.clip(np.round((X - xs2[0]) / r2).astype(int), 0, len(xs2) - 1)
        ii = np.clip(np.round((Y - ys2[0]) / r2).astype(int), 0, len(ys2) - 1)
        I = np.clip(ii[:, None] + di[None, :], 0, len(ys2) - 1)
        J = np.clip(jj[:, None] + dj[None, :], 0, len(xs2) - 1)
        return (H2[I, J] - prof[None, :]).max(1) + 0.02

    xr = np.arange(-47.0, 47.0 + 1e-9, a.finish_pitch)
    yr = np.arange(-32.0, 32.0 + 1e-9, a.finish_step)
    g0(xr[0], yr[0])
    g0(z=SAFE)
    first = True
    for i, y in enumerate(yr):
        X = xr if i % 2 == 0 else xr[::-1]
        Z = drop(X, np.full(len(X), y))
        Z = np.maximum(Z, -0.3)
        if first:
            g0(z=Z[0] + 2)
            g1(z=Z[0], F=600)
            first = False
        else:
            g1(X[0], y, Z[0])
        for j in range(1, len(X)):
            g1(X[j], y, Z[j], F=1500 if j == 1 and i == 0 else None)
    g0(z=SAFE + 20)
    emit("M9")
    emit("M5")
    emit("M30")
    emit("%")
    Path(a.out).write_text("\n".join(OUT) + "\n")
    print(f"{a.out}: {len(OUT)} lines")


if __name__ == "__main__":
    main()
